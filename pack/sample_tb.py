def build(path: str | Path, tweak: dict | None = None) -> pd.DataFrame:
    rows = []
    for code, name, cur, prv in ACCTS:
        if tweak and code in tweak:
            cur = cur + tweak[code]
        rows.append({
            "كود الحساب": code, "اسم الحساب": name,
            "مدين": cur if cur > 0 else 0, "دائن": -cur if cur < 0 else 0,
            "السنة السابقة": prv,
        })
    df = pd.DataFrame(rows)
    df.to_excel(path, index=False)
    return df


